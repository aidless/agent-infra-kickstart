def _render_report(topic: str, extraction: Dict[str, Any]) -> str:
    lines = [f"# Report: {topic}", "", f"- Topic: {topic}", f"- Files analyzed: {extraction.get('total_files', 0)}", ""]
    lines.append("## Top keywords")
    for kw, cnt in extraction.get("top_keywords", []):
        lines.append(f"- {kw}: {cnt}")
    lines.append("")
    lines.append("## Per-file stats")
    for f in extraction.get("files", []):
        hits = f.get("topic_hits") or {}
        hit_str = ", ".join([f"{k}={v}" for k, v in hits.items()]) if hits else "n/a"
        lines.append(f"- {Path(f.get('path','')).name}: lines={f.get('lines')} chars={f.get('chars')} words={f.get('words')} topic_hits=({hit_str})")
    lines.append("")
    lines.append("## Notes")
    lines.append("- Generated by minimal agent loop (stateful, resumable, traced).")
    lines.append("- Replace with real retrieval/tools for production scenarios.")
    return "\n".join(lines) + "\n"


def default_plan(topic: str, input_dir: str = "sample_input") -> List[Step]:
    return [
        Step(
            step_id=new_id("step"),
            name="list_inputs",
            tool="list_files",
            args={"directory": input_dir, "glob": "*"},
            idempotency_key=f"list_inputs:v1:{input_dir}",
        ),
        Step(
            step_id=new_id("step"),
            name="extract_info",
            tool="extract_keywords",
            args={"paths_from_step": "list_inputs", "topic": topic, "top_n": 8},
            idempotency_key=f"extract_info:v1:{topic}",
        ),
        Step(
            step_id=new_id("step"),
            name="write_report",
            tool="write_text",
            args={"path": "report.md", "content_from_step": "extract_info", "topic": topic},
            idempotency_key=f"write_report:v1:{topic}",
        ),
        Step(
            step_id=new_id("step"),
            name="summarize_report",
            tool="summarize_text",
            args={"path": "report.md", "preview_chars": 200},
            idempotency_key="summarize_report:v1",
        ),
    ]


def create_session(store: Store, goal: str, steps: List[Step], *, input_dir: Optional[str] = None, topic: Optional[str] = None) -> Session:
    session = Session(session_id=new_id("sess"), goal=goal, steps=steps, input_dir=input_dir, topic=topic)
    store.save(session)
    store.append_event(session.session_id, "session.created", {"goal": goal, "steps": [s.name for s in steps], "input_dir": input_dir, "topic": topic})
    return session


def _find_step(session: Session, name: str) -> Optional[Step]:
    for s in session.steps:
        if s.name == name:
            return s
    return None


def _resolve_args(session: Session, step: Step) -> Dict[str, Any]:
    args = dict(step.args)
    if "paths_from_step" in args:
        src = _find_step(session, args.pop("paths_from_step"))
        paths: List[str] = []
        if src and isinstance(src.output, dict):
            for f in src.output.get("files", []) or []:
                if isinstance(f, dict) and f.get("path"):
                    paths.append(f["path"])
        args["paths"] = paths
    if "content_from_step" in args:
        src = _find_step(session, args.pop("content_from_step"))
        topic = args.pop("topic", session.topic or "")
        extraction = src.output if src and isinstance(src.output, dict) else {"total_files": 0, "top_keywords": [], "files": []}
        args["content"] = _render_report(topic, extraction)
    return args


def _args_summary(args: Dict[str, Any]) -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    for k, v in args.items():
        if k == "content" and isinstance(v, str):
            out[k] = f"<str:{len(v)} chars>"
        elif isinstance(v, list):
            out[k] = f"<list:{len(v)}>"
        elif isinstance(v, str) and len(v) > 120:
            out[k] = v[:117] + "..."
        else:
            out[k] = v
    return out


def backoff_delay_ms(attempt: int, base_ms: int, cap_ms: int) -> int:
    """Delay before retry number `attempt` (1-based: after the first failure).

    Exponential: base * 2**(attempt-1), clamped to cap_ms. base_ms=0 turns the
    delay off while keeping the schedule observable in the trace, which is what
    the eval suite uses: the suite cares that the schedule is computed and
    recorded, not that this machine actually waited.
    """
    if base_ms <= 0:
        return 0
    raw = base_ms * (2 ** (attempt - 1))
    return min(raw, cap_ms) if cap_ms > 0 else raw


def _sleep_ms(ms: int) -> None:
    if ms > 0:
        time.sleep(ms / 1000.0)


def run_session(
    store: Store,
    session: Session,
    *,
    fail_on_step: str | None = None,
    max_retries: int = 0,
    default_timeout_ms: int | None = None,
    backoff_base_ms: int = 0,
    backoff_cap_ms: int = 4000,
    price_id: str = DEFAULT_PRICE_ID,
) -> Session:
    # A resume over an already-complete plan is a no-op. Without this guard the run
    # would still emit a second session.succeeded event, making the event log
    # unusable as an append-only record of what actually happened.
    if session.status == "succeeded" and all(s.status == "succeeded" for s in session.steps):
        return session

    run_dir = store.session_dir(session.session_id)
    input_dir = Path(session.input_dir).resolve() if session.input_dir else None
    registry = build_default_registry(run_dir, input_dir=input_dir)
    session.status = "running"
    store.save(session)

    for step in session.steps:
        if step.status == "succeeded":
            continue  # resume: skip completed steps

        resolved_args = _resolve_args(session, step)

        if fail_on_step and step.name == fail_on_step:
            step.status = "failed"
            step.error = f"simulated failure at {step.name}"
            step.error_code = "SIMULATED"
            step.ended_at = now_iso()
            step.duration_ms = 0
            session.status = "interrupted"
            store.append_event(session.session_id, "step.failed", {"step": step.name, "error": step.error, "error_code": step.error_code})
            store.append_trace(session.session_id, {
                "step": step.name,
                "tool": step.tool,
                "status": "failed",
                "error_code": step.error_code,
                "duration_ms": 0,
                "attempt": 0,
                "args": _args_summary(resolved_args),
                **measure_output(None),
                **cost_fields(resolved_args, None, price_id),
            })
            store.save(session)
            return session

        attempts = 0
        while True:
            attempts += 1
            step.status = "running"
            step.started_at = now_iso()
            step.error = None
            step.error_code = None
            store.append_event(session.session_id, "step.started", {"step": step.name, "tool": step.tool, "attempt": attempts})
            store.save(session)
            t0 = time.perf_counter()
            budget = step.timeout_ms if step.timeout_ms is not None else default_timeout_ms
            token = set_deadline(budget / 1000.0 if budget else None)
            try:
                tool = registry.get(step.tool)
                result: ToolResult = tool(**resolved_args)
                if result.ok:
                    step.status = "succeeded"
                    step.output = result.output
                    step.error = None
                    step.error_code = None
                else:
                    step.status = "failed"
                    step.error = result.error
                    step.error_code = getattr(result, "error_code", None)
            except Exception as e:  # noqa: BLE001
                step.status = "failed"
                step.error = repr(e)
                step.error_code = "EXCEPTION"
            finally:
                clear_deadline(token)
            step.duration_ms = int((time.perf_counter() - t0) * 1000)
            step.ended_at = now_iso()
            store.append_event(session.session_id, f"step.{step.status}", {"step": step.name, "error": step.error, "error_code": step.error_code, "duration_ms": step.duration_ms, "attempt": attempts})
            store.append_trace(session.session_id, {
                "step": step.name,
                "tool": step.tool,
                "status": step.status,
                "error_code": step.error_code,
                "duration_ms": step.duration_ms,
                "attempt": attempts,
                "args": _args_summary(resolved_args),
                **measure_output(step.output),
                **cost_fields(resolved_args, step.output, price_id),
            })
            store.save(session)
            if step.status == "succeeded":
                break
            if attempts <= max_retries:
                delay_ms = backoff_delay_ms(attempts, backoff_base_ms, backoff_cap_ms)
                store.append_event(session.session_id, "step.retry_scheduled", {
                    "step": step.name,
                    "next_attempt": attempts + 1,
                    "error_code": step.error_code,
                    "delay_ms": delay_ms,
                })
                _sleep_ms(delay_ms)
                continue
            if attempts > max_retries:
                # retryable failure classes leave the rest of the plan pending so
                # a later run_session can resume instead of rebuilding the plan.
                session.status = "interrupted" if step.error_code in RETRYABLE_ERROR_CODES else "failed"
                store.save(session)
                store.append_event(session.session_id, f"session.{session.status}", {"at_step": step.name, "error_code": step.error_code})
                return session

    # ── finish guards（harness 改造 1+2，来源见 agent/finish_guard.py 头部）──
    # 空 diff guard + pre-stop verifier：终态前必须自证，否则不记 succeeded。
    # 不改任务提示词（Table IV：prompt-only 行把未验证退出抬到 30%，是反例）。
    g = prestop_verify(
        run_dir,
        produced_paths=_produced_paths(session),
        py_files=_touched_py_files(run_dir),
        verify_cmd=os.environ.get("AIK_VERIFY_CMD"),
        verify_timeout_s=float(os.environ.get("AIK_VERIFY_TIMEOUT_S", "120")),
    )
    # guard 结果只落 event（append-only 日志），不写进 trace：
    # trace 每行都带 token/rate 成本字段，且与 state.steps 一一对应；
    # guard 不是任务步骤，硬塞进去会破坏既有「trace 可复算成本」不变量。
    store.append_event(session.session_id, "finish_guard.checked", g.as_dict())
    if not g.ok:
        # Session 没有 error 字段（dataclass 固定字段集，额外属性不会落盘），
        # 失败原因全部走 event + trace，由 append-only 日志承载。
        session.status = "failed"
        store.append_event(session.session_id, "session.blocked_by_guard",
                           {"code": g.code, "detail": g.detail})
        store.save(session)
        return session

    session.status = "succeeded"
    store.append_event(session.session_id, "session.succeeded", {"steps": len(session.steps)})
    store.save(session)
    return session


def _produced_paths(session: Session) -> List[str]:
    """本次 session 实际写出的产物路径（write_text 返回 written=True 的那些）。"""
    out: List[str] = []
    for s in session.steps:
        o = s.output
        if isinstance(o, dict) and o.get("written") and o.get("path"):
            out.append(str(o["path"]))
    return out


def _touched_py_files(run_dir: Path) -> List[str]:
    """run_dir 下属于本次产出的 .py（只做编译自检，不执行）。"""
    if not run_dir.exists():
        return []
    return [str(p) for p in sorted(run_dir.rglob("*.py"))]
